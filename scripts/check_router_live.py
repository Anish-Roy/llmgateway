"""Manual check: are the cheap alias's answers good enough on the prompts `auto` sends it?
Calls the real providers; not for CI.

Takes prompts from data/queries.jsonl that the router sends to the cheap alias:
    - every hard prompt it sends there (the router's mistakes, where quality is most at risk);
    - a fixed sample of easy ones (the bulk of what it sends there).
Each is asked twice through a running gateway, with the cache off: as `model: "auto"`, which
must come back routed to the cheap alias (x-gateway-route), and as the strong alias. Both
answers go side by side into a Markdown file, to be read and judged by a person: this script
doesn't score anything.

uv run uvicorn app.main:app            # with GROQ_API_KEY / GEMINI_API_KEY in .env
GATEWAY_API_KEY=gw-... uv run python -m scripts.check_router_live --pause 2.5

Groq's free tier allows 30 requests a minute per model; past it, `fast` falls back to Gemini,
which the x-gateway-provider column shows. --pause keeps under it.
"""

import argparse
import hashlib
import os
import time
from pathlib import Path

from openai import OpenAI

from app.config import Settings
from app.routing.auto import ROUTE_HEADER, AutoRouter
from app.routing.registry import load_registry
from app.usage import tokens
from scripts.eval_router import Prompt, decide, load_prompts
from scripts.eval_semantic_cache import DATASET

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "router_spotcheck.md"


def sample(prompts: list[Prompt], router: AutoRouter, easy: int) -> list[Prompt]:
    to_cheap = [p for p in prompts if decide(router, p).alias == router.spec.cheap]
    hard = [p for p in to_cheap if p.hard]
    # A fixed sample, by hash: the same prompts on every run.
    easy_ones = sorted(
        (p for p in to_cheap if not p.hard), key=lambda p: hashlib.sha256(p.id.encode()).digest()
    )[:easy]
    return sorted(hard + easy_ones, key=lambda p: p.id)


def ask(client: OpenAI, model: str, prompt: str, max_tokens: int) -> tuple[str, dict]:
    raw = client.chat.completions.with_raw_response.create(
        model=model,
        messages=[{"role": "user", "content": prompt}],
        max_tokens=max_tokens,
        extra_headers={"x-gateway-cache": "off"},
    )
    reply = raw.parse()
    return reply.choices[0].message.content or "", dict(raw.headers)


def quote(answer: str) -> str:
    """An answer as a blockquote, so its own headings stay inside it."""
    return "\n".join(f"> {line}".rstrip() for line in answer.strip().splitlines())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--base-url", default="http://localhost:8000/v1")
    parser.add_argument("--easy", type=int, default=15, help="easy prompts to sample")
    parser.add_argument("--max-tokens", type=int, default=1024)
    parser.add_argument("--pause", type=float, default=0, help="seconds between calls")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    config = load_registry(Settings(_env_file=None).models_file)
    if config.auto is None:
        raise SystemExit("config/models.yaml has no `auto` section")
    tokens.load_encoding()
    router = AutoRouter(config.auto)
    prompts = sample(load_prompts(DATASET), router, args.easy)
    client = OpenAI(api_key=os.environ["GATEWAY_API_KEY"], base_url=args.base_url, max_retries=0)

    sections = []
    for i, p in enumerate(prompts, 1):
        label = "hard" if p.hard else "easy"
        print(f"[{i}/{len(prompts)}] {p.id} ({label}, {p.category})", flush=True)
        cheap, cheap_headers = ask(client, "auto", p.text, args.max_tokens)
        if cheap_headers.get(ROUTE_HEADER) != config.auto.cheap:
            raise SystemExit(f"{p.id}: the gateway routed it to {cheap_headers.get(ROUTE_HEADER)}")
        time.sleep(args.pause)
        strong, strong_headers = ask(client, config.auto.strong, p.text, args.max_tokens)
        time.sleep(args.pause)
        sections.append(
            f"## {p.id} ({label}, {p.category})\n\n**Prompt:** {p.text}\n\n"
            f"### auto -> {config.auto.cheap} ({cheap_headers.get('x-gateway-provider')})\n\n"
            f"{quote(cheap)}\n\n"
            f"### {config.auto.strong} ({strong_headers.get('x-gateway-provider')})\n\n"
            f"{quote(strong)}\n"
        )

    hard = sum(p.hard for p in prompts)
    args.out.write_text(
        "# Router spot-check\n\n"
        f"Generated by `scripts/check_router_live.py`: {len(prompts)} prompts that `auto` sends "
        f"to `{config.auto.cheap}` ({hard} labelled hard, {len(prompts) - hard} easy), each "
        f"answered by `{config.auto.cheap}` (through `auto`) and by `{config.auto.strong}`, "
        f"cache off, max_tokens {args.max_tokens}. The verdict is in docs/decisions.md.\n\n"
        + "\n".join(sections),
        encoding="utf-8",
    )
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
